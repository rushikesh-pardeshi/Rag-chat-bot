    async def test_the_name_is_locked_before_anything_is_written(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        admin: User,
    ) -> None:
        """The deadlock guard, pinned at the one place it has to hold: lock order.

        Supersession writes the rows of *other* documents while the pipeline holds
        `pg_advisory_xact_lock('audit_chain:<tenant>')`. Another pipeline can hold one of
        those rows while waiting for that same chain lock, which is a cycle PostgreSQL
        resolves by aborting one of them — rolling back a document that had already embedded
        and upserted, so its chunk rows vanish while its vectors do not and nothing can
        enumerate them again. `lock_name` removes the cycle by making both transactions order
        their locks identically, and it only does that if it is taken *first*.

        Asserted on the call order rather than on concurrency, because the fake has one
        session and no transactions. The two `lock_name` tests in `test_ingestion_pool.py`
        are the real proof, and they need PostgreSQL.
        """
        await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )

        # Twice, and that is correct: `upload` claims the name before it reads `next_version`
        # or writes a row, and `_run_pipeline` claims it again because it also runs as a
        # worker with no upload around it. Advisory locks are re-entrant within a
        # transaction, so the second acquisition costs nothing on the inline path.
        assert documents.name_locks == [
            (admin.tenant_id, "policy.pdf"),
            (admin.tenant_id, "policy.pdf"),
        ]
        # Before the first write, which is what makes it a lock *order* rather than merely a
        # lock. `set_parse_result`/`set_status` are the first writes either path makes.
        assert documents.write_order[0] == "lock_name"

