"""backend/tests/test_document_service.py

Role: Unit tests for the Phase 3 document lifecycle — upload validation, storage keys,
parsing, chunk citability, soft-delete/restore, role and tenant visibility, and the audit rows
each of those writes.

**No test here contacts AWS.** `FakeS3Client` replaces the boto3 client while
`S3StorageService` stays real, so `build_key` and `sanitize_filename` — the two functions that
stand between a caller-supplied filename and an object key — are exercised rather than mocked
out. The document fixtures are generated by `backend/tests/document_fixtures.py`, so what each
file contains is readable in the test that uses it.

The tests are grouped by the property they defend, and several are here for a specific reason
worth stating:

  * `TestMagicByteValidation` — an `.exe` renamed `.pdf` must be refused before any parser
    sees it, and nothing must reach S3. This is the control from
    `.claude/rules/secure-coding-vapt.md` against handing an attacker-supplied file to a
    parsing library.
  * `TestFilenameSafety` — `../../etc/passwd` and its Windows spelling must land inside the
    document's own prefix. An escaped key in a shared bucket is a cross-tenant write.
  * `TestCitability` — every chunk must carry a page number or a section label, because BR-03
    says an answer must cite where it came from, and a chunk that cannot be cited must not
    exist.
  * `TestAuditPrivacy` — no filename, no document text, in any audit `detail`. A document name
    can carry a customer identifier.
"""

