class TestFilenameSafety:
    @pytest.mark.parametrize(
        ("supplied", "expected_name"),
        [
            ("../../../etc/passwd.pdf", "passwd.pdf"),
            ("..\\..\\windows\\system32\\config.pdf", "config.pdf"),
            ("C:\\Users\\analyst\\Desktop\\report.pdf", "report.pdf"),
            ("/absolute/path/statement.pdf", "statement.pdf"),
            ("....//....//escape.pdf", "escape.pdf"),
            # Surrounding whitespace is stripped before substitution, so the extension the
            # allowlist reads is still `pdf` and not `pdf_`.
            ("  spaced name.pdf  ", "spaced_name.pdf"),
            ("..pdf.pdf", "pdf.pdf"),
        ],
    )
    async def test_a_traversal_filename_lands_inside_the_documents_own_prefix(
        self,
        service: DocumentService,
        admin: User,
        supplied: str,
        expected_name: str,
    ) -> None:
        document = await service.upload(
            actor=admin, context=CONTEXT, filename=supplied, data=TWO_PAGE_PDF
        )
        assert document.name == expected_name
        assert document.s3_key == f"documents/{document.id}/v1/{expected_name}"
        # The two properties that matter, asserted independently of the format above.
        assert ".." not in document.s3_key
        assert document.s3_key.startswith(f"documents/{document.id}/")

    def test_sanitization_never_produces_an_empty_component(self) -> None:
        """An empty name would collapse the key to a bare directory prefix."""
        for hostile in ["", "...", "/", "..", "///", "\\", "._-"]:
            assert sanitize_filename(hostile) == "document"

    def test_a_unicode_lookalike_separator_does_not_survive(self) -> None:
        """NFKD folds the look-alike; the allowlist removes whatever is left.

        U+2044 FRACTION SLASH normalizes to `/`, which is then treated as a path separator.
        Enumerating dangerous characters would miss the next look-alike; an allowlist does not.
        """
        assert "/" not in sanitize_filename("report\u2044\u2044etc\u2044passwd.pdf")
        assert sanitize_filename("full\uff0fwidth.pdf") == "width.pdf"

    def test_a_very_long_name_is_capped_but_keeps_its_extension(self) -> None:
        """The extension is what the allowlist check reads, so truncation must preserve it."""
        result = sanitize_filename("a" * 400 + ".pdf")
        assert len(result) <= 180
        assert result.endswith(".pdf")


class TestVersionLineage:
    async def test_re_uploading_a_name_writes_v2_and_keeps_v1_bytes_and_lineage(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        s3: FakeS3Client,
        admin: User,
    ) -> None:
        """Our IAM role cannot enable bucket versioning, so lineage is app-side.

        Overwriting would destroy the earlier bytes, which is the one thing lineage exists to
        prevent — and the earlier bytes are what an existing audit reference points at. v1 is
        *retired* from search once v2 is live (see `TestVersionSupersession`), which is a
        different thing from being erased: the object, the row and the lineage all survive.
        """
        first = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )
        second = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=REVISED_PDF
        )

        assert (first.version, second.version) == (1, 2)
        assert first.s3_key != second.s3_key
        assert first.s3_key.endswith("/v1/policy.pdf")
        assert second.s3_key.endswith("/v2/policy.pdf")
        # Both objects still present. Retiring a version is a status change, not a deletion.
        assert sorted(s3.keys()) == sorted([first.s3_key, second.s3_key])
        # The row is still there to be listed and restored.
        assert first.id in documents.documents

        versions = await service.list_versions("policy.pdf", actor=admin)
        assert [d.version for d in versions] == [1, 2]

    async def test_a_soft_deleted_version_number_is_not_reused(
        self, service: DocumentService, admin: User
    ) -> None:
        """Reusing v2 would put two different files behind one lineage identifier."""
        first = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )
        await service.soft_delete(first.id, actor=admin, context=CONTEXT)
        second = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )
        assert second.version == 2


class TestVersionSupersession:
    """`DOCUMENT_SUPERSEDE_PREVIOUS_VERSIONS`: one searchable copy of the same bytes.

    Without it, re-uploading a document left every previous revision `ACTIVE` and indexed:
    the same passage citable twice, an answer able to attribute one claim to two versions of
    one document, and stale copies competing for the `RAG_TOP_K` retrieval slots a current
    document needed.

    **Identity is the content, not the filename.** The name selects the candidates and
    `content_hash` decides, because nothing in a filename or in the bytes distinguishes "a
    corrected revision of this document" from "a different document that happens to be called
    `invoice.pdf`". So the automatic rule only ever acts on the unambiguous case — same name,
    same bytes — and a version that diverges is reported for a human instead. The two tests
    that matter most here are the pair that pin those opposite outcomes.

    The rule lives in `document_service.supersede_previous_versions` and is called by the
    pipeline, not by `upload` — which is what the "v2 never became searchable" test pins.
    """

    async def test_an_identical_re_upload_retires_the_previous_one_and_drops_its_vectors(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        index: FakePineconeIndex,
        admin: User,
    ) -> None:
        """The unambiguous case: the same bytes under the same name are redundant."""
        first = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )
        namespace = get_settings().pinecone_namespace(admin.tenant_id)
        assert len(index.namespaces[namespace]) == 2  # v1 indexed its two chunks

        second = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )

        assert documents.documents[first.id].status is DocumentStatus.DELETED
        assert documents.documents[second.id].status is DocumentStatus.ACTIVE
        # Only v2's chunks are left in the index. This is the assertion that matters: a
        # retired version that kept its vectors would still be found by Pinecone, and the
        # database re-check in the RAG path would then silently drop the match — correct, but
        # at the cost of a retrieval slot on every query.
        remaining = index.namespaces[namespace]
        chunks = await documents.get_chunks(second.id, admin.tenant_id)
        assert set(remaining) == {str(chunk.id) for chunk in chunks}

    async def test_a_same_named_document_with_different_content_stays_searchable(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        index: FakePineconeIndex,
        admin: User,
    ) -> None:
        """The case that makes filename-based retirement wrong, pinned so it cannot regress.

        Two unrelated documents can share a filename. Retiring one because a newer upload
        reused the name would remove a live document from search on the strength of a guess —
        and silently, which in a banking corpus is worse than leaving a duplicate: a duplicate
        is visible in the answer, an absence is not.
        """
