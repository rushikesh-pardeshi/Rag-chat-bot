class TestAuditPrivacy:
    async def test_no_audit_detail_ever_contains_the_filename_or_document_text(
        self, service: DocumentService, audit_repo: FakeAuditRepository, admin: User
    ) -> None:
        """A document name can carry a customer identifier; chunk text is the document body.

        `.claude/rules/secure-coding-vapt.md` forbids either in a log, so the audit trail
        records *which* object was acted on and not what was inside it.
        """
        secret_name = "acct-4417829930-statement.pdf"
        document = await service.upload(
            actor=admin, context=CONTEXT, filename=secret_name, data=TWO_PAGE_PDF
        )
        await service.preview(document.id, actor=admin, context=CONTEXT)
        await service.soft_delete(document.id, actor=admin, context=CONTEXT)
        await service.restore(document.id, actor=admin, context=CONTEXT)

        serialized = repr(_details(audit_repo))
        assert "4417829930" not in serialized
        assert "statement" not in serialized
        assert "Interest Rate Policy" not in serialized
        # Every entry still identifies its object precisely.
        assert all(e.object_id == str(document.id) for e in audit_repo.entries)

    async def test_every_document_action_is_audited_with_actor_and_object(
        self, service: DocumentService, audit_repo: FakeAuditRepository, admin: User
    ) -> None:
        document = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )
        await service.soft_delete(document.id, actor=admin, context=CONTEXT)
        await service.restore(document.id, actor=admin, context=CONTEXT)

        actions = [e.action for e in audit_repo.entries]
        assert AuditAction.DOCUMENT_UPLOAD in actions
        assert AuditAction.DOCUMENT_DELETE in actions
        assert AuditAction.DOCUMENT_RESTORE in actions
        for entry in audit_repo.entries:
            # Attribution splits by who actually acted. Request-originated rows carry the
            # administrator's own address and request context; the ingestion pipeline's rows
            # carry the subsystem address, because a background worker claiming the uploader's
            # email for a row they were not present for is a false record. `user_id` still
            # points at the administrator on both — it answers "whose upload caused this".
            if (entry.detail or {}).get("phase") == AUDIT_PHASE_INGEST:
                assert entry.actor_email == INGESTION_ACTOR_EMAIL
                # `audit_log.ip_address` is NOT NULL and a worker has no client address, so
                # the service substitutes its placeholder rather than borrowing the request's.
                assert entry.ip_address == UNKNOWN_IP
            else:
                assert entry.actor_email == admin.email
                assert entry.ip_address == CONTEXT.ip_address
            assert entry.user_id == admin.id
            assert entry.object_type == AuditObjectType.DOCUMENT.value

    async def test_the_audit_chain_stays_verifiable_across_the_whole_lifecycle(
        self, service: DocumentService, audit_repo: FakeAuditRepository, admin: User
    ) -> None:
        """The chain is what makes the log tamper-*evident*, not merely append-only."""
        audit = AuditService(audit_repo)
        document = await service.upload(
            actor=admin, context=CONTEXT, filename="policy.pdf", data=TWO_PAGE_PDF
        )
        await service.soft_delete(document.id, actor=admin, context=CONTEXT)
        await service.restore(document.id, actor=admin, context=CONTEXT)

        assert (await audit.verify_chain(admin.tenant_id)).is_valid

        # Edit one stored row the way a tampering attempt would, and the check localizes it.
        audit_repo.entries[1].outcome = AuditOutcome.FAILURE
        result = await audit.verify_chain(admin.tenant_id)
        assert not result.is_valid
        assert result.first_failure is not None
        assert result.first_failure[0] == audit_repo.entries[1].log_id



class TestABulkUpload:
    """Twenty-five documents in one batch, end to end: stored, parsed, embedded, searchable.

    Asserted rather than assumed, because "it will handle 25 files" is a claim about four
    different limits at once and only one of them is visible in the UI:

      * the browser transfers `CONCURRENT_UPLOADS` at a time and queues the rest;
      * the pool ingests `INGEST_LOCAL_CONCURRENCY` at a time and parks the rest
        (`test_ingestion_pool.py` covers that half, with a 25-document case of its own);
      * `BedrockClient` holds a process-wide semaphore of `MAX_CONCURRENT_CALLS`, so embedding
        cannot fan out past it however many documents are in flight;
      * nothing in between drops a document on the floor.

    This test covers the last one, which is the one a user would notice: every document that
    was accepted has to end up answerable. It runs the *real* pipeline — `FakeIngestionQueue`
    calls `ingest_document_in_session` — against fake S3, fake Bedrock and `FakePineconeIndex`,
    so no network is involved and the assertion is about this code rather than about AWS.
    """

    #: Enough to exceed every concurrency limit in play (3 transfers, 4 ingestion slots, 8
    #: Bedrock calls) several times over, which is what makes it a batch test rather than a
    #: repetition of the single-document one.
    COUNT = 25

    async def test_every_document_in_a_batch_of_25_becomes_searchable(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        index: FakePineconeIndex,
        admin: User,
    ) -> None:
        uploaded = []
        for number in range(self.COUNT):
            # Distinct names *and* distinct content: a shared name would exercise version
            # supersession instead, and identical bytes would only prove the duplicate flag.
            uploaded.append(
                await service.upload(
                    actor=admin,
                    context=CONTEXT,
                    filename=f"statement_{number:02d}.pdf",
                    data=make_pdf(
                        [
                            f"Account statement {number}. The closing balance is "
                            f"{1000 + number} USD.",
                            f"Page two of statement {number}. Interest applied monthly.",
                        ]
                    ),
                )
            )

        assert len(uploaded) == self.COUNT
        # Every one of them, not "most": a batch that silently loses the 23rd document is the
        # failure this is here to catch.
        assert [d.status for d in uploaded] == [DocumentStatus.ACTIVE] * self.COUNT
        assert len({d.id for d in uploaded}) == self.COUNT
        assert len({d.s3_key for d in uploaded}) == self.COUNT

    async def test_every_chunk_of_every_document_reaches_the_vector_store(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        index: FakePineconeIndex,
        admin: User,
    ) -> None:
        """The half that matters for answering: indexed, in this tenant's namespace, all of it.

        `ACTIVE` with missing vectors is the specific failure the pipeline is ordered to
        prevent — a document that is listed, looks healthy and answers every question about
        itself with "not found". Counting chunk rows against vector ids is what proves it did
        not happen under load.
        """
        expected_chunk_ids: set[str] = set()
        for number in range(self.COUNT):
            document = await service.upload(
                actor=admin,
                context=CONTEXT,
                filename=f"statement_{number:02d}.pdf",
                data=make_pdf(
                    [
                        f"Account statement {number}. The closing balance is "
                        f"{1000 + number} USD.",
                        f"Page two of statement {number}. Interest applied monthly.",
                    ]
                ),
            )
            chunks = await documents.get_chunks(document.id, admin.tenant_id)
            assert chunks, f"document {number} became ACTIVE with no chunk rows"
            expected_chunk_ids.update(str(chunk.id) for chunk in chunks)

        namespace = get_settings().pinecone_namespace(admin.tenant_id)
        # Exact set equality in both directions: no chunk missing from the index, and no
        # orphan vector in it either.
        assert set(index.namespaces[namespace]) == expected_chunk_ids
        assert len(expected_chunk_ids) == self.COUNT * 2  # two pages, two chunks, each

    async def test_one_unparseable_document_does_not_cost_the_other_24(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        admin: User,
    ) -> None:
        """A realistic batch contains a scan. It must not take the batch down with it.

        `service` has no OCR client, so `SCANNED_PDF` lands `NEEDS_OCR` with nothing indexed —
        which is the honest outcome for a page image here, and must stay a fact about that one
        document rather than an exception that abandons the files queued behind it.
        """
        statuses = []
        for number in range(self.COUNT):
            data = SCANNED_PDF if number == 7 else make_pdf([f"Readable page {number}."])
            document = await service.upload(
                actor=admin,
                context=CONTEXT,
                filename=f"mixed_{number:02d}.pdf",
                data=data,
            )
            statuses.append(document.status)

        assert statuses[7] is DocumentStatus.NEEDS_OCR
        assert [s for i, s in enumerate(statuses) if i != 7] == [DocumentStatus.ACTIVE] * (
            self.COUNT - 1
        )
