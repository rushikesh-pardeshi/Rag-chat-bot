class TestParseFailure:
    async def test_a_zip_that_is_not_a_docx_fails_the_document_not_the_request_silently(
        self,
        service: DocumentService,
        documents: FakeDocumentRepository,
        s3: FakeS3Client,
        audit_repo: FakeAuditRepository,
        admin: User,
    ) -> None:
        """Sniffing cannot tell a DOCX from any other ZIP; `parse_docx` is what catches it.

        By then the object is already stored, so the outcome must be a `FAILED` row an
        Administrator can see — not a silent absence — and an audit entry recording why.

        **The request itself succeeds.** In Phase 3 `upload()` parsed inline and this raised.
        Phase 4 moved parsing into the ingestion pipeline, whose failures are swallowed by
        `IngestionQueue.enqueue` on purpose: the bytes *are* stored and the row *does* exist,
        so raising would make an administrator re-upload and get a v2 they did not want. The
        `FAILED` status and the audit row are how the failure surfaces instead.
        """
        document = await service.upload(
            actor=admin,
            context=CONTEXT,
            filename="quarterly.docx",
            data=make_zip_that_is_not_docx(),
        )

        stored = list(documents.documents.values())
        assert len(stored) == 1
        assert stored[0].status is DocumentStatus.FAILED
        assert document.status is DocumentStatus.FAILED
        # The bytes stay: an orphaned row with no object is worse than a failed row with one.
        assert s3.keys() == [stored[0].s3_key]

        failure = audit_repo.entries[-1]
        assert failure.action is AuditAction.DOCUMENT_UPLOAD
        assert failure.outcome is AuditOutcome.FAILURE
        assert failure.detail is not None
        assert failure.detail["phase"] == AUDIT_PHASE_INGEST
        assert failure.detail["reason"] == "parse_failed"
        # The exception's code, never its message: a parser message can quote file structure.
        # `parse_docx` refuses a ZIP with no `word/document.xml` as an unsupported type, so
        # this is the more specific subclass rather than the base `validation_error`.
        assert failure.detail["error_code"] == "unsupported_document_type"

    async def test_the_failure_is_attributed_to_the_uploader_but_not_impersonated(
        self,
        service: DocumentService,
        audit_repo: FakeAuditRepository,
        admin: User,
    ) -> None:
        """A background worker is the actor; the uploader is the subject.

        `user_id` is the administrator whose upload caused the work, so a compliance reviewer
        can join the failure to the person. `actor_email` is the subsystem, because claiming
        the administrator's own address for a row they were not present for would be a false
        record in a table that is supposed to be evidence.
        """
        await service.upload(
            actor=admin,
            context=CONTEXT,
            filename="quarterly.docx",
            data=make_zip_that_is_not_docx(),
        )
        failure = audit_repo.entries[-1]
        assert failure.user_id == admin.id
        assert failure.actor_email == "system@docquery.ingestion"
        # Not a routable address, so nothing can be sent to it by mistake.
        assert "@docquery.ingestion" in failure.actor_email

    async def test_no_vectors_are_written_for_a_document_that_failed_to_parse(
        self,
        service: DocumentService,
        index: FakePineconeIndex,
        admin: User,
    ) -> None:
        """`ACTIVE` is set last precisely so this holds. Nothing reached the embedder."""
        await service.upload(
            actor=admin,
            context=CONTEXT,
            filename="quarterly.docx",
            data=make_zip_that_is_not_docx(),
        )
        assert index.total() == 0


