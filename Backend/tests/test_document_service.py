def _details(audit_repo: FakeAuditRepository) -> list[dict]:
    return [entry.detail or {} for entry in audit_repo.entries]


def _ingest_rows(audit_repo: FakeAuditRepository) -> list[dict]:
    """Audit details written by the ingestion pipeline rather than by the request.

    Both use `AuditAction.DOCUMENT_UPLOAD` — there is no `DOCUMENT_INGEST` member, because
    adding one to a native PostgreSQL enum needs an `ALTER TYPE` migration — so `detail.phase`
    is what tells them apart.
    """
    return [
        entry.detail or {}
        for entry in audit_repo.entries
        if (entry.detail or {}).get("phase") == AUDIT_PHASE_INGEST
    ]


